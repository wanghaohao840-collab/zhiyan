from __future__ import annotations

import logging
import re
from collections.abc import Callable
from time import perf_counter
from typing import Any, Literal, TypedDict
from uuid import UUID, uuid4


logger = logging.getLogger(__name__)
_CITATION_MARKER = re.compile(r"\[(S-[0-9a-fA-F]{12}|G-[0-9a-fA-F]{10})\]")
_UNVERIFIED_CITATION = "[未核实引用]"


class SummaryCancelled(RuntimeError):
    """The owning process requested cooperative cancellation."""


class SummaryProgressAborted(RuntimeError):
    """The progress consumer withdrew permission to continue the workflow."""


SummaryOutputIssue = Literal["output_truncated", "safety_blocked", "empty_output", "abnormal_finish"]
_OUTPUT_MESSAGES = {
    "output_truncated": "模型输出达到额度上限",
    "safety_blocked": "模型未正常结束输出",
    "empty_output": "模型未返回可用内容",
    "abnormal_finish": "模型未正常结束输出",
}


class IncompleteSummaryOutput(RuntimeError):
    """A completion ended without a usable document summary."""

    def __init__(self, category: SummaryOutputIssue, *, invalid_citations: int = 0) -> None:
        super().__init__(_OUTPUT_MESSAGES[category])
        self.category = category
        self.invalid_citations = invalid_citations


def verify_summary_citations(text: str, allowed_ids: set[str]) -> tuple[str, int]:
    """Mark unknown system citations in model output and require usable prose."""
    invalid_count = 0

    def replace(match: re.Match[str]) -> str:
        nonlocal invalid_count
        if match[1] in allowed_ids:
            return match[0]
        invalid_count += 1
        return _UNVERIFIED_CITATION

    verified = _CITATION_MARKER.sub(replace, text)
    body = _CITATION_MARKER.sub("", verified).replace(_UNVERIFIED_CITATION, "")
    if body != verified and not any(character.isalnum() for character in body):
        raise IncompleteSummaryOutput("empty_output", invalid_citations=invalid_count)
    return verified, invalid_count


class SummaryState(TypedDict, total=False):
    document_count: int
    graph_by_document: dict[str, dict[str, Any]]
    shared_graph_contexts: list[dict[str, Any]]
    shared_graph_sources: list[dict[str, Any]]
    completed: dict[str, dict[str, Any]]
    failures: dict[str, str]
    mapped: list[dict[str, Any]]
    retryable: bool
    incomplete_output: bool
    output_issues: dict[str, int]
    invalid_citations: int
    error_category: Literal["context_capacity"]
    error: str
    answer: str
    truncated: bool


SummaryStage = Callable[[SummaryState], SummaryState]


def run_summary_workflow(
    prepare: SummaryStage,
    map_documents: SummaryStage,
    collect: SummaryStage,
    reduce: SummaryStage,
    *,
    use_langgraph: bool,
    document_count: int,
    job_id: str | None = None,
    attempt: int | None = None,
) -> SummaryState:
    stages = (
        ("prepare", prepare),
        ("map_documents", map_documents),
        ("collect", collect),
        ("reduce", reduce),
    )
    initial: SummaryState = {"document_count": document_count}

    run_id = uuid4().hex
    # Only UUIDs generated by the job repository are eligible for correlation.
    try:
        safe_job_id = str(UUID(job_id)) if isinstance(job_id, str) else None
    except ValueError:
        safe_job_id = None
    safe_attempt = attempt if safe_job_id and type(attempt) is int and attempt > 0 else None

    def traced(name: str, stage: SummaryStage, engine: str) -> SummaryStage:
        def node(state: SummaryState) -> SummaryState:
            started = perf_counter()
            status, reason = "error", "stage_error"
            update: SummaryState = {}
            rejected_citations = 0
            try:
                update = stage(state)
                if "error" not in update:
                    status, reason = "ok", "none"
                elif update.get("error_category") == "context_capacity":
                    reason = "context_capacity"
                return update
            except IncompleteSummaryOutput as error:
                reason = error.category if error.category in _OUTPUT_MESSAGES else "abnormal_finish"
                rejected_citations = error.invalid_citations
                raise
            except SummaryCancelled:
                status, reason = "cancelled", "cancelled"
                raise
            except SummaryProgressAborted:
                status, reason = "cancelled", "progress_aborted"
                raise
            finally:
                elapsed_ms = round((perf_counter() - started) * 1000, 1)
                mapped = update.get("mapped", state.get("mapped", []))
                failed = len(update.get("failures", state.get("failures", {})))
                if "completed" in update:
                    mapped = [
                        item for item in update["completed"].values()
                        if item["status"] == "ok"
                    ]
                    failed = document_count - len(mapped)
                cache_hits = sum(bool(item.get("cache_hit")) for item in mapped)
                issues = {
                    key: update["output_issues"][key]
                    for key in _OUTPUT_MESSAGES
                    if key in update.get("output_issues", {})
                }
                invalid_citations = update.get("invalid_citations", state.get("invalid_citations", 0))
                invalid_citations += rejected_citations
                logger.info(
                    "qa_summary stage=%s status=%s duration_ms=%s run_id=%s "
                    "job_id=%s attempt=%s engine=%s reason=%s output_issues=%s "
                    "documents=%s mapped=%s failed=%s cache_hits=%s truncated=%s invalid_citations=%s",
                    name,
                    status,
                    elapsed_ms,
                    run_id,
                    safe_job_id,
                    safe_attempt,
                    engine,
                    reason,
                    issues,
                    document_count,
                    len(mapped),
                    failed,
                    cache_hits,
                    update.get("truncated", False),
                    invalid_citations,
                    extra={
                        "qa_summary_stage": name,
                        "qa_summary_status": status,
                        "qa_summary_run_id": run_id,
                        "qa_summary_job_id": safe_job_id,
                        "qa_summary_attempt": safe_attempt,
                        "qa_summary_engine": engine,
                        "qa_summary_reason": reason,
                        "qa_summary_output_issues": issues,
                        "qa_summary_invalid_citations": invalid_citations,
                    },
                )

        return node

    def run_direct(engine: str) -> SummaryState:
        for name, stage in stages:
            initial.update(traced(name, stage, engine)(initial))
            if "error" in initial:
                break
        return initial

    if not use_langgraph:
        return run_direct("direct")

    from langchain_core.globals import get_debug
    from langgraph.graph import END, START, StateGraph
    from langsmith import tracing_context

    # LangChain's global debug console can print inputs even with tracing off.
    if get_debug():
        logger.warning(
            "qa_summary_workflow_disabled reason=langchain_debug run_id=%s job_id=%s attempt=%s",
            run_id,
            safe_job_id,
            safe_attempt,
        )
        with tracing_context(enabled=False):
            return run_direct("langgraph_debug_fallback")

    def route(state: SummaryState) -> Literal["continue", "stop"]:
        return "stop" if "error" in state else "continue"

    graph = StateGraph(SummaryState)
    for name, stage in stages:
        graph.add_node(name, traced(name, stage, "langgraph"))
    graph.add_edge(START, "prepare")
    graph.add_conditional_edges(
        "prepare", route, {"continue": "map_documents", "stop": END}
    )
    graph.add_edge("map_documents", "collect")
    graph.add_conditional_edges("collect", route, {"continue": "reduce", "stop": END})
    graph.add_edge("reduce", END)

    # Invocation data includes document text. Keep tracing local even if
    # LangSmith tracing was enabled elsewhere in this process.
    with tracing_context(enabled=False):
        return graph.compile().invoke(initial)
